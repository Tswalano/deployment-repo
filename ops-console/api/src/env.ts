import { announce } from './alerts';
import { aws, dryRun } from './aws';
import { InstanceRow } from './collector';
import { DeployError } from './deploys';
import { classify, ROTATE_DOCUMENT } from './secrets';

/** An app's environment variables = SSM parameters under /apps/<service>/ (loaded into the app at start). */
export const KEY_RE = /^[A-Z][A-Z0-9_]{0,63}$/;

function serviceOf(inst: InstanceRow, project: string): string {
    const app = inst.last_status?.apps.find((a) => a.project === project);
    if (!app) throw new DeployError(`${project} isn't an app on ${inst.name}.`, 404);
    if (/^(ops-console|ops-dashboard)/.test(app.service)) throw new DeployError('The console never edits its own settings.', 403);
    return app.service;
}

export async function listEnv(inst: InstanceRow, project: string) {
    const service = serviceOf(inst, project);
    const a = aws();
    if (!a.listParameters) throw new DeployError('Environment variables are not available.');
    const params = await a.listParameters(inst.region, `/apps/${service}`);
    const url = params.find((p) => p.name.endsWith('/DATABASE_URL'));
    const dbRole = url && a.getParameter ? /^[a-z]+:\/\/([^:/@]+):/.exec((await a.getParameter(inst.region, url.name).catch(() => null)) ?? '')?.[1] ?? null : null;
    return {
        service, dbRole,
        vars: params.map((p) => {
            const key = p.name.split('/').pop()!;
            return { key, kind: classify(key), version: p.version, lastModified: p.lastModified, lastModifiedBy: p.lastModifiedBy,
                generated: ['db', 'jwt'].includes(classify(key)) };
        }).sort((x, y) => x.key.localeCompare(y.key)),
        dryRun,
    };
}

export async function revealEnv(inst: InstanceRow, project: string, key: string): Promise<string> {
    const service = serviceOf(inst, project);
    if (!KEY_RE.test(key)) throw new DeployError('Invalid name.');
    const v = await aws().getParameter!(inst.region, `/apps/${service}/${key}`);
    if (v === null) throw new DeployError('No such variable.', 404);
    return v;
}

const parse = (out: string) => { try { return JSON.parse(out.trim().split('\n').pop() ?? '{}'); } catch { return { ok: false, error: out.slice(0, 200) }; } };
async function reload(inst: InstanceRow, service: string) {
    return parse(await aws().runDocument(inst.region, inst.aws_instance_id, ROTATE_DOCUMENT, { kind: ['reload'], target: [service] }, 300_000)
        .catch((err) => JSON.stringify({ ok: false, error: (err as Error).message })));
}

/**
 * Add, change (value) or remove (value === null) one variable, then restart the app and check its health.
 * If the app doesn't come back healthy, the previous state is restored (old value back, or the new variable removed).
 */
export async function setEnv(inst: InstanceRow, project: string, key: string, value: string | null, by: string) {
    const service = serviceOf(inst, project);
    if (!KEY_RE.test(key)) throw new DeployError('Names use capital letters, digits and underscores, starting with a letter (e.g. PAYSTACK_SECRET_KEY).');
    if (['db', 'jwt'].includes(classify(key)) && value !== null) throw new DeployError(`${key} is generated by the console: use Rotate instead of typing a value.`);
    if (value !== null && (value.length > 4096 || /[\r\n]/.test(value))) throw new DeployError('Values are a single line, up to 4096 characters.');
    const a = aws();
    const name = `/apps/${service}/${key}`;
    const old = await a.getParameter!(inst.region, name);
    if (value === null && old === null) throw new DeployError('No such variable.', 404);
    if (value !== null && old === value) throw new DeployError('That is already the value.');
    if (value === null) await a.deleteParameter!(inst.region, name); else await a.putParameter!(inst.region, name, value);
    const r = await reload(inst, service);
    const verb = value === null ? 'removed' : old === null ? 'added' : 'changed';
    if (!r.ok) {
        if (old === null) await a.deleteParameter!(inst.region, name); else await a.putParameter!(inst.region, name, old);
        await reload(inst, service);
        await announce(`[ENV] ${key} change on ${project} was rolled back`, `${by} ${verb} ${key} on ${project} (${inst.name}), but the app was unhealthy afterwards (${r.error ?? JSON.stringify(r.health)}). The previous state was restored.`, 'env');
        throw new DeployError(`${project} was unhealthy after the change, so it was undone. ${r.error ?? ''}`.trim(), 409);
    }
    await announce(`[ENV] ${key} ${verb} on ${project}`, `${by} ${verb} ${key} on ${project} (${inst.name})${dryRun ? ' (dry run: nothing was written)' : ''}; the app restarted and is healthy.`, 'env');
    return { ok: true, key, verb, dryRun };
}
